// Downloads the Google Sheet as CSV and regenerates models.js.
// Usage: npm run sync
const fs = require("fs");
const path = require("path");
const imageOverrides = require("../image-overrides");

const SHEET_ID = "1XAwkb2OxNZIunkwcPv0YPVVLwCGMxHXVuXr42Q0MIoM";
const GID = "0";
const CSV_URL = `https://docs.google.com/spreadsheets/d/${SHEET_ID}/export?format=csv&gid=${GID}`;
const OUT_FILE = path.join(__dirname, "..", "models.js");

// Minimal CSV parser that handles quoted fields, escaped quotes and CRLF.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') inQuotes = false;
      else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (c !== "\r") field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

function slugify(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

async function main() {
  const res = await fetch(CSV_URL);
  if (!res.ok) throw new Error(`Failed to download sheet: HTTP ${res.status}`);
  const [header, ...rows] = parseCsv(await res.text());

  const modelCol = header.findIndex((h) => h.trim().toLowerCase() === "model");
  const imageCol = header.findIndex((h) => h.trim().toLowerCase() === "image");
  if (modelCol === -1 || imageCol === -1) throw new Error("Sheet must have 'Model' and 'Image' columns");

  const seen = new Map();
  const models = [];
  for (const r of rows) {
    const name = (r[modelCol] || "").trim();
    if (!name) continue;
    let slug = slugify(name);
    // Keep slugs unique if two names normalise to the same slug
    const count = seen.get(slug) || 0;
    seen.set(slug, count + 1);
    if (count) slug = `${slug}-${count + 1}`;
    const image = (r[imageCol] || "").trim() || imageOverrides[name] || null;
    models.push({ id: models.length + 1, slug, name, image });
  }

  const body =
    "// AUTO-GENERATED by scripts/sync-from-sheet.js — do not edit by hand.\n" +
    `// Source: https://docs.google.com/spreadsheets/d/${SHEET_ID}\n` +
    `module.exports = ${JSON.stringify(models, null, 2)};\n`;
  fs.writeFileSync(OUT_FILE, body);

  const missing = models.filter((m) => !m.image).length;
  console.log(`Wrote ${models.length} models to models.js (${missing} without an image).`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
